"""
Migraciones contra un PostgreSQL de verdad (en el CI lo levanta el job). Se saltean sin DATABASE_URL.

Son tests sincrónicos a propósito: alembic/env.py corre las migraciones con asyncio.run, que no puede llamarse
desde un loop que ya está corriendo.
"""

import asyncio
import os
from pathlib import Path

import pytest
from alembic.config import Config
from sqlalchemy import inspect, text
from sqlalchemy.exc import IntegrityError
from sqlalchemy.ext.asyncio import create_async_engine

from alembic import command
from app.core.config import async_database_url

DATABASE_URL = os.environ.get("DATABASE_URL")
pytestmark = pytest.mark.skipif(not DATABASE_URL, reason="sin DATABASE_URL (en el CI hay un Postgres)")

ROOT = Path(__file__).resolve().parents[1]
TABLES = {
    "wallets",
    "point_transactions",
    "server_boosts",
    "server_boost_counters",
    "subscriptions",
    "idempotency_records",
    "outbox_events",
}


def alembic_config() -> Config:
    config = Config(str(ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(ROOT / "alembic"))
    config.attributes["database_url"] = DATABASE_URL
    return config


def run(coro):
    return asyncio.run(coro)


async def table_names() -> set[str]:
    engine = create_async_engine(async_database_url(DATABASE_URL))
    try:
        async with engine.connect() as conn:
            return set(await conn.run_sync(lambda sync: inspect(sync).get_table_names()))
    finally:
        await engine.dispose()


async def execute(*statements: str) -> None:
    """Corre las sentencias en una transacción que siempre se deshace (no deja datos)."""
    engine = create_async_engine(async_database_url(DATABASE_URL))
    try:
        async with engine.connect() as conn:
            transaction = await conn.begin()
            try:
                for statement in statements:
                    await conn.execute(text(statement))
            finally:
                await transaction.rollback()
    finally:
        await engine.dispose()


@pytest.fixture(scope="module", autouse=True)
def migrated_database():
    config = alembic_config()
    command.downgrade(config, "base")
    command.upgrade(config, "head")
    yield config
    # Queda migrada para los demás tests
    command.upgrade(config, "head")


def test_upgrade_crea_todas_las_tablas():
    assert TABLES <= run(table_names())


def test_los_modelos_coinciden_con_la_migracion(migrated_database):
    # Falla (AutogenerateDiffsDetected) si un modelo cambió sin su migración, o al revés
    command.check(migrated_database)


def test_el_saldo_no_puede_quedar_negativo():
    with pytest.raises(IntegrityError, match="ck_wallets_balance_non_negative"):
        run(execute("INSERT INTO wallets (user_id, balance) VALUES ('u1', -1)"))


def test_una_compra_tiene_que_traer_el_paquete_y_el_pago():
    with pytest.raises(IntegrityError, match="ck_point_transactions_purchase_details"):
        run(
            execute(
                "INSERT INTO wallets (user_id, balance) VALUES ('u1', 500)",
                "INSERT INTO point_transactions (id, user_id, kind, amount, balance_after) "
                "VALUES (gen_random_uuid(), 'u1', 'purchase', 500, 500)",
            )
        )


def test_un_mismo_cobro_no_acredita_dos_veces():
    purchase = (
        "INSERT INTO point_transactions (id, user_id, kind, amount, balance_after, package_id, price_cents, "
        "currency, payment_reference) VALUES (gen_random_uuid(), 'u1', 'purchase', 500, {after}, 'points_500', "
        "499, 'USD', 'ch_1')"
    )
    with pytest.raises(IntegrityError, match="uq_point_transactions_payment_reference"):
        run(
            execute(
                "INSERT INTO wallets (user_id, balance) VALUES ('u1', 1000)",
                purchase.format(after=500),
                purchase.format(after=1000),
            )
        )


def test_un_usuario_tiene_una_sola_suscripcion_viva():
    subscription = (
        "INSERT INTO subscriptions (id, user_id, plan, status, current_period_start, current_period_end) "
        "VALUES (gen_random_uuid(), 'u1', 'monthly', '{status}', now(), now() + interval '30 days')"
    )
    # Una vencida no cuenta
    run(execute(subscription.format(status="expired"), subscription.format(status="active")))
    with pytest.raises(IntegrityError, match="uq_subscriptions_live_user_id"):
        run(execute(subscription.format(status="active"), subscription.format(status="past_due")))


def test_el_nivel_de_boost_va_de_0_a_3():
    with pytest.raises(IntegrityError, match="ck_server_boost_counters_level_valid"):
        run(execute("INSERT INTO server_boost_counters (server_id, active_boosts, level) VALUES ('s1', 40, 4)"))


def test_downgrade_borra_todo_y_upgrade_lo_vuelve_a_crear(migrated_database):
    command.downgrade(migrated_database, "base")
    assert not (TABLES & run(table_names()))
    command.upgrade(migrated_database, "head")
    assert TABLES <= run(table_names())
